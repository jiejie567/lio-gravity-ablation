def paired_effects(S, method, metric):
    ratios = []
    for seq, _ in CORE:
        runs = S[seq]["runs"]
        ratios.append(runs[method][metric] / runs["A"][metric])
    return np.asarray(ratios, dtype=float)


def interaction(S, metric):
    values = []
    for seq, _ in CORE:
        r = S[seq]["runs"]
        a = r["A"][metric]
        value = ((r["RED18"][metric] - a) - (r["RED21"][metric] - a)
                 - (r["RED20"][metric] - a)) / a
        values.append(100 * value)
    return np.asarray(values)


def effect(S, seq, method, metric, repeats=False):
    runs = S[seq]["runs"]
    a = med(runs, "A", metric, repeats)
    x = med(runs, method, metric, repeats)
    return 100 * (x / a - 1)


