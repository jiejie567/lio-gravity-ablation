def liosam_state_sequences(strengthening):
    block = strengthening["liosam_new_sequences"]
    sequences = block["previous_sequences"] + block["new_sequences"]
    if len(sequences) != block["total_sequence_units"]:
        raise RuntimeError("LIO-SAM state-ablation sequence count is inconsistent")
    return sequences


def usable(rec):
    return rec.get("usable", True) is not False


def repeat_values(runs, method, metric, include_repeats=True):
    values = []
    pattern = re.compile(rf"^{re.escape(method)}_r\d+$")
    for name, rec in runs.items():
        if name != method and not (include_repeats and pattern.match(name)):
            continue
        if usable(rec) and rec.get(metric) is not None:
            values.append(float(rec[metric]))
    return values


def med(runs, method, metric, include_repeats=True):
    values = repeat_values(runs, method, metric, include_repeats)
    return float(np.median(values)) if values else None


def fmt_ate(value):
    if value is None:
        return "--"
    return f"{value:.3f}" if value < 1 else f"{value:.2f}"


def pct(value):
    return f"{value:+.1f}"


